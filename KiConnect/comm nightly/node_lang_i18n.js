// Serialize back to JS
function serializeObj(obj, indent) {
  const lines = [];
  for (const [k, v] of Object.entries(obj)) {
    const escaped = v.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
    lines.push(indent + "    '" + k + "': '" + escaped + "',");
  }
  return lines.join('\n');
}

